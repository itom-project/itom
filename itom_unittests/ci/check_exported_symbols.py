#!/usr/bin/env python3
"""Compares the exported symbols of the public itom libraries with a reference list.

Why this script exists:
    AGENTS.md: the public API and ABI of itomCommonLib, itomCommonQtLib, dataobject, itomShapeLib
    and itomCommonPlotLib must stay stable. Plugins and designer plugins are compiled against these
    libraries and load them at runtime. A removed or renamed exported function breaks every plugin
    that uses it, mostly without a compile error in this repository.

What is compared:
    The defined, exported symbols of every shared library, read with 'nm -D' (Linux). Symbols are
    split into two groups:
    - strong symbols (nm types T, D, B, R): ordinary out-of-line functions and data. A strong symbol
      that is listed in the reference and missing in the build FAILS the check.
    - weak symbols (nm types W, V, u): implicit template instantiations, inline functions that the
      compiler did not inline, vtables and typeinfo. Which of them exist depends on the compiler,
      the optimization level and on which code uses them, so a missing weak symbol is only
      reported as a NOTICE.
    Symbols of the std library, of the compiler runtime and of OpenCV/Qt instantiations are
    ignored (only the 'ito' namespace and C functions are checked).
    New symbols are allowed (the API may grow) and are reported as a notice.

Usage:
    python3 check_exported_symbols.py --build-dir build --reference itom_unittests/ci/abi
    python3 check_exported_symbols.py --build-dir build --reference itom_unittests/ci/abi --update

Reference files:
    <reference>/<library>.linux-x86_64.txt, one symbol per line, the first column is 'strong' or
    'weak'. Update them with --update when a symbol has been added on purpose or when a symbol
    has been removed in a major version (see AGENTS.md), and review the diff.
"""

import argparse
import os
import platform
import re
import subprocess
import sys

LIBRARIES = ["dataobject", "itomCommonLib", "itomCommonQtLib", "itomShapeLib", "itomCommonPlotLib"]

STRONG_TYPES = set("TDBR")
WEAK_TYPES = set("WVu")

# Only symbols of the itom API are checked: everything in the namespace 'ito' (functions, methods,
# vtables, typeinfo, thunks of multiple inheritance), the few exported classes in the global
# namespace (e.g. ItomSharedSemaphore) and unmangled C functions. Symbols of the std library, of
# OpenCV, of Qt and of the compiler runtime are not part of the API.
INCLUDED = re.compile(
    r"^(_ZN3ito|_ZNK3ito|_ZTVN3ito|_ZTIN3ito|_ZTSN3ito|_ZThn\d+_N3ito|_ZTv\d+_n\d+_N3ito"
    r"|_ZN\d+Itom|_ZNK\d+Itom|_ZTV\d+Itom|_ZTI\d+Itom|_ZTS\d+Itom"
    r"|[A-Za-z][A-Za-z0-9_]*$)"
)


def platform_suffix():
    return f"{platform.system().lower()}-{platform.machine().lower()}"


def library_path(build_dir, name):
    for candidate in (
        os.path.join(build_dir, "lib%s.so" % name),
        os.path.join(build_dir, "lib", "lib%s.so" % name),
    ):
        if os.path.isfile(candidate):
            return candidate
    return None


def read_symbols(path):
    """returns {symbol name: 'strong' | 'weak'} of the exported, defined symbols of a shared library."""
    out = subprocess.run(["nm", "-D", "--defined-only", path], capture_output=True, text=True, check=True).stdout
    symbols = {}
    for line in out.splitlines():
        parts = line.split()
        if len(parts) < 3:
            continue
        kind, name = parts[1], parts[2]
        if "@" in name:
            name = name.split("@", 1)[0]
        if not INCLUDED.match(name):
            continue
        if kind in STRONG_TYPES:
            symbols[name] = "strong"
        elif kind in WEAK_TYPES:
            symbols[name] = "weak"
    return symbols


def reference_path(reference_dir, name):
    return os.path.join(reference_dir, f"{name}.{platform_suffix()}.txt")


def read_reference(path):
    symbols = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            kind, name = line.split(None, 1)
            symbols[name.strip()] = kind
    return symbols


def write_reference(path, symbols):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("# exported symbols, generated by check_exported_symbols.py --update. Do not edit by hand.\n")
        f.write("# strong: must not disappear (ABI break). weak: compiler dependent, only a notice.\n")
        for name in sorted(symbols):
            f.write(f"{symbols[name]} {name}\n")


def demangle(names):
    if not names:
        return {}
    out = subprocess.run(["c++filt"] + list(names), capture_output=True, text=True).stdout.splitlines()
    return dict(zip(names, out)) if len(out) == len(names) else {n: n for n in names}


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--build-dir", required=True, help="folder with the built shared libraries")
    parser.add_argument("--reference", required=True, help="folder with the reference symbol lists")
    parser.add_argument("--lib", action="append", help="library name (default: all public libraries)")
    parser.add_argument("--update", action="store_true", help="write the current symbols as new reference")
    args = parser.parse_args()

    if platform.system() != "Linux":
        print("This check only supports Linux (nm -D). Use dumpbin /exports on Windows.")
        return 2

    ok = True
    rows = []
    for name in args.lib or LIBRARIES:
        path = library_path(args.build_dir, name)
        print("\n===== %s =====" % name, flush=True)
        if path is None:
            print(f"::error::lib{name}.so was not found in {args.build_dir}")
            ok = False
            rows.append((name, "-", "-", "-", "-", "not built"))
            continue

        current = read_symbols(path)
        ref_path = reference_path(args.reference, name)

        if args.update:
            write_reference(ref_path, current)
            print("reference written: %s (%d symbols)" % (ref_path, len(current)))
            rows.append((name, len(current), "-", "-", "-", "updated"))
            continue

        if not os.path.isfile(ref_path):
            print("::error::no reference file %s. Create it with --update." % ref_path)
            ok = False
            rows.append((name, len(current), "-", "-", "-", "no reference"))
            continue

        reference = read_reference(ref_path)
        missing_strong = sorted(n for n, k in reference.items() if k == "strong" and n not in current)
        missing_weak = sorted(n for n, k in reference.items() if k == "weak" and n not in current)
        added = sorted(n for n in current if n not in reference)
        demangled = demangle(missing_strong + missing_weak + added)

        for n in missing_strong:
            print(f"::error::{name}: exported symbol removed (ABI break): {demangled[n]}")
        for n in missing_weak:
            print(f"::notice::{name}: weak symbol missing (compiler dependent, check if intended): {demangled[n]}")
        for n in added:
            print(f"::notice::{name}: new exported symbol ({current[n]}): {demangled[n]}")
        if added or missing_weak:
            print("Run 'check_exported_symbols.py --update' and commit the reference if these changes are intended.")

        if missing_strong:
            ok = False
        status = "FAILED" if missing_strong else "ok"
        rows.append((name, len(current), len(missing_strong), len(missing_weak), len(added), status))

    summary = ["| Library | Symbols | Removed (strong) | Missing (weak) | New | Result |", "|---|---|---|---|---|---|"]
    summary += ["| %s | %s | %s | %s | %s | %s |" % r for r in rows]
    print("\n" + "\n".join(summary))
    step_summary = os.environ.get("GITHUB_STEP_SUMMARY")
    if step_summary:
        with open(step_summary, "a", encoding="utf-8") as f:
            f.write("## Exported symbols of the public libraries\n\n" + "\n".join(summary) + "\n")

    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
